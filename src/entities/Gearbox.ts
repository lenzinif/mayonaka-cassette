import type { BeatJudgement, BeatJudgementTier } from '@src/audio/BeatClock';
import { tuning } from '@src/config/tuning';

export type GearNumber = 1 | 2 | 3 | 4 | 5 | 6;

export const MAX_GEAR: GearNumber = 6;
export const GEAR_NUMBERS: readonly GearNumber[] = [1, 2, 3, 4, 5, 6];

export interface ShiftResult {
  fromGear: GearNumber;
  toGear: GearNumber;
  direction: 'up' | 'down';
  prevRpm: number;
  newRpm: number;
  judgement: BeatJudgement;
  /** True when the shift was performed in the valid RPM window and not spammed on the same beat. */
  validForBonus: boolean;
  /** Effective reward tier (`'OFF'` if `validForBonus` is false). */
  rewardTier: BeatJudgementTier;
  /** Longitudinal jerk impulse generated by the RPM transition (feeds MelonSoda in Tofu Mode). */
  shiftJerk: number;
}

/**
 * 6-speed arcade beat-shift gearbox (AGENTS.md §3 & §4.8, docs/DESIGN.md §4).
 *
 * Pure TypeScript module (zero React imports).
 * - 6 gears with tunable top-speed ratios `[0.24, 0.40, 0.56, 0.72, 0.86, 1.00] * maxSpeed`.
 * - Fake torque curve peaking around 0.74 RPM with progressive high-gear taper (`tuning.accelTaper`),
 *   pronounced low-RPM lugging in higher gears, and a soft redline limiter at 1.0 RPM.
 * - Timestamp-based beat judgement on manual shifts (`PERFECT` / `GOOD` / `OFF`).
 * - Reward is strictly Groove + filter blip (no Mario Kart speed/torque boost).
 * - Optional Auto-Shift Assist (`autoShift`), plus automatic stall-prevention drop to 1st gear.
 */
export class Gearbox {
  gear: GearNumber = 1;
  rpm = 0;
  autoShift = false;

  /** Last manual shift result for HUD display. */
  lastShift: ShiftResult | null = null;

  /** Prevents spamming upshift/downshift on the exact same beat for duplicate Groove. */
  private lastBonusBeatIndex = -999999;

  reset(): void {
    this.gear = 1;
    this.rpm = 0;
    this.lastShift = null;
    this.lastBonusBeatIndex = -999999;
  }

  /** Returns the top-speed ratio `(0..1]` of `gear` relative to `tuning.maxSpeed`. */
  getGearRatio(gear: GearNumber = this.gear): number {
    switch (gear) {
      case 1:
        return tuning.gear1MaxRatio;
      case 2:
        return tuning.gear2MaxRatio;
      case 3:
        return tuning.gear3MaxRatio;
      case 4:
        return tuning.gear4MaxRatio;
      case 5:
        return tuning.gear5MaxRatio;
      case 6:
        return tuning.gear6MaxRatio;
    }
  }

  /** Returns the top speed in world units/s for `gear`. */
  getGearTopSpeed(maxSpeed: number, gear: GearNumber = this.gear): number {
    return Math.max(1, maxSpeed * this.getGearRatio(gear));
  }

  /** Computes normalized RPM `[0, 1.1]` for a given `speed` and `gear`. */
  computeRpm(speed: number, maxSpeed: number, gear: GearNumber = this.gear): number {
    const top = this.getGearTopSpeed(maxSpeed, gear);
    return Math.max(0, Math.min(1.1, speed / top));
  }

  /**
   * Returns the lower RPM boundary of `gear`'s active turbo powerband.
   * Derived from the hand-off speed of `gear - 1` so dropping below the previous gear's
   * shift window causes authentic off-boost lugging unless the player downshifts.
   */
  getBandStartRpm(gear: GearNumber = this.gear): number {
    if (gear <= 1) return 0;
    const prevRatio = this.getGearRatio((gear - 1) as GearNumber);
    const curRatio = this.getGearRatio(gear);
    return (prevRatio / Math.max(0.01, curRatio)) * 0.74;
  }

  /**
   * True when `gear > 1` and current RPM has dropped below `gear`'s operating powerband
   * (engine is off-boost / bogging and needs a downshift).
   */
  isLugging(speed: number, maxSpeed: number, gear: GearNumber = this.gear): boolean {
    if (gear <= 1) return false;
    const rpm = this.computeRpm(speed, maxSpeed, gear);
    return rpm < this.getBandStartRpm(gear);
  }

  /**
   * Returns the ideal gear `(1..6)` that places `speed` squarely inside the turbo powerband.
   */
  getOptimalGearForSpeed(speed: number, maxSpeed: number): GearNumber {
    for (let g = 1; g < MAX_GEAR; g++) {
      const gear = g as GearNumber;
      if (this.computeRpm(speed, maxSpeed, gear) <= 0.88) {
        return gear;
      }
    }
    return MAX_GEAR;
  }

  /**
   * Fake torque curve multiplier `[0, 1.18]` at the current speed & gear:
   * - In 1st gear, strong launch torque from 0 RPM (`>= 0.92`) so standing starts feel snappy.
   * - In gears 2–6, each gear has a real operating band starting at `getBandStartRpm(gear)`.
   *   Dropping below `bandStart` drops the engine off-boost into severe low-RPM lugging (`0.12..0.56`),
   *   making downshifts essential on `build` climbs, after `breakdown` hairpins/drifts, or after collisions.
   * - Turbo powerband peaks at `0.74..0.82` RPM.
   * - Progressive mechanical taper (`tuning.accelTaper`) spaces gears across musical bars.
   * - Soft redline limiter fades torque smoothly to `0` as RPM approaches `1.0`.
   */
  getTorqueFactor(speed: number, maxSpeed: number): number {
    const rpm = this.computeRpm(speed, maxSpeed, this.gear);
    this.rpm = rpm;

    if (rpm >= 1.0) {
      return 0;
    }

    const gearProgress = (this.gear - 1) / (MAX_GEAR - 1);
    const taperMultiplier = Math.max(
      0.32,
      1 - Math.pow(gearProgress, 1.1) * tuning.accelTaper * 0.65,
    );

    // Soft redline roll-off between 0.91 and 1.00 RPM
    if (rpm > 0.91) {
      const redlineProgress = (rpm - 0.91) / 0.09;
      return Math.max(0, (1 - redlineProgress * redlineProgress) * 0.92 * taperMultiplier);
    }

    if (this.gear === 1) {
      // Snappy 1st gear launch with bell peak at 0.74 RPM
      const distFromPeak1 = rpm - 0.74;
      const bell1 = Math.exp(-(distFromPeak1 * distFromPeak1) / 0.09);
      return Math.max(0.92, 0.78 + 0.36 * bell1);
    }

    const bandStart = this.getBandStartRpm(this.gear);
    const peakRpm = 0.74 + gearProgress * 0.08;

    // Off-boost lugging when RPM falls below the gear's operating band
    if (rpm < bandStart) {
      const lugRatio = Math.max(0, rpm / Math.max(0.1, bandStart));
      const lugFloor = Math.max(0.12, 0.36 - gearProgress * 0.24);
      const lugCurve = Math.pow(lugRatio, 2.2);
      return (lugFloor + lugCurve * (0.56 - lugFloor)) * taperMultiplier;
    }

    // Active turbo powerband above bandStart
    const distFromPeak = rpm - peakRpm;
    const bell = Math.exp(-(distFromPeak * distFromPeak) / 0.042);
    const spoolRamp = Math.min(1, (rpm - bandStart) / Math.max(0.08, peakRpm - bandStart));
    const inBandBase = 0.56 + 0.24 * spoolRamp;
    return (inBandBase + 0.38 * bell) * taperMultiplier;
  }

  /**
   * Advances RPM state and handles Auto-Shift Assist or manual stall protection.
   */
  update(speed: number, maxSpeed: number): void {
    this.rpm = this.computeRpm(speed, maxSpeed, this.gear);
    const speedRatio = maxSpeed > 0 ? speed / maxSpeed : 0;

    if (this.autoShift) {
      if (this.gear < MAX_GEAR && this.rpm >= 0.9) {
        this.gear = (this.gear + 1) as GearNumber;
        this.rpm = this.computeRpm(speed, maxSpeed, this.gear);
      } else if (this.gear > 1) {
        const lowerGear = (this.gear - 1) as GearNumber;
        const lowerRpm = this.computeRpm(speed, maxSpeed, lowerGear);
        const bandStart = this.getBandStartRpm(this.gear);
        if (this.rpm < Math.max(0.58, bandStart) && lowerRpm <= 0.88) {
          this.gear = lowerGear;
          this.rpm = lowerRpm;
        }
      }
      return;
    }

    // Manual mode stall protection: if the car slows to a crawl, drop to 1st gear automatically
    if (this.gear > 1 && speedRatio < 0.12) {
      this.gear = 1;
      this.rpm = this.computeRpm(speed, maxSpeed, 1);
    }
  }

  /**
   * Performs a manual upshift or downshift and evaluates beat timing (docs/DESIGN.md §4).
   * Returns `null` if already in 6th (on upshift) or 1st (on downshift).
   */
  shift(
    direction: 'up' | 'down',
    speed: number,
    maxSpeed: number,
    judgement: BeatJudgement,
  ): ShiftResult | null {
    const fromGear = this.gear;
    if (direction === 'up' && fromGear >= MAX_GEAR) return null;
    if (direction === 'down' && fromGear <= 1) return null;

    const toGear = (direction === 'up' ? fromGear + 1 : fromGear - 1) as GearNumber;
    const prevRpm = this.computeRpm(speed, maxSpeed, fromGear);
    const newRpm = this.computeRpm(speed, maxSpeed, toGear);

    // Check whether the shift makes mechanical sense (prevents spamming Q/E for free Groove)
    const isFreshBeat =
      judgement.beatIndex !== this.lastBonusBeatIndex || this.lastBonusBeatIndex === -999999;
    const rpmValid =
      direction === 'up'
        ? prevRpm >= 0.72
        : prevRpm <= 0.84 && newRpm >= 0.48 && newRpm <= 0.96 && speed > maxSpeed * 0.08;

    const validForBonus = rpmValid && isFreshBeat;
    const rewardTier: BeatJudgementTier = validForBonus ? judgement.tier : 'OFF';

    if (validForBonus && (rewardTier === 'PERFECT' || rewardTier === 'GOOD')) {
      this.lastBonusBeatIndex = judgement.beatIndex;
    }

    this.gear = toGear;
    this.rpm = newRpm;

    // Smoothly timed shifts produce less jerk than off-beat or over-revving shifts
    const rpmDelta = Math.abs(newRpm - prevRpm);
    const smoothnessFactor =
      rewardTier === 'PERFECT' ? 0.45 : rewardTier === 'GOOD' ? 0.7 : 1.15;
    const overRevPenalty = direction === 'down' && newRpm >= 0.98 ? 1.6 : 1.0;
    const shiftJerk =
      (direction === 'up' ? -1 : 1) * rpmDelta * 2.4 * smoothnessFactor * overRevPenalty;

    const result: ShiftResult = {
      fromGear,
      toGear,
      direction,
      prevRpm,
      newRpm,
      judgement,
      validForBonus,
      rewardTier,
      shiftJerk,
    };
    this.lastShift = result;
    return result;
  }
}
